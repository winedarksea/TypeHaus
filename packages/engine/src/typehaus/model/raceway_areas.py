def table_4_row(material: str, trade_in: float) -> FillRow:
    """The printed row; ``KeyError`` for a material or size the print did not carry."""
    for size, row in TABLE_4[material].items():
        if abs(size - trade_in) < 1e-3:  # nominals arrive as metres and back
            return row
    raise KeyError(f"Table 4 {material}: no printed row for {trade_in:g} in.")
